#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Build libVerifiedRootKey.a: the kernel's trusted owner anchor and the VerifiedRoot verifier (iPadOS-Padpipa-6).

Replaces the unpublished builder that UniXNU-pipa's board.toml names ("build-verified-root-key.py --pin <sha256>").
It is written from the public pieces only:

  kits/VerifiedRoot/src/verified_root.c      vr_open / vr_verify_block (envelope parser, the code the host test runs)
  kits/VerifiedRoot/adapters/xnu_crypto.c    vr_xnu_crypto: SHA-256 and RSA-3072 PKCS#1 v1.5 through libkern
  the owner anchor (395 bytes)               verified_root_key, read by PipaUfs (NativeUfs.cpp) and NativeVirtioBlock

and the symbols those drivers import (PipaUfs NativeUfs.cpp lines 14-16, VirtioMmioBlock NativeVirtioBlock.cpp 25-28).
verified_root_manifest is EMPTY on purpose: on pipa the owner-signed envelopes come from the userdata policy directory
(SHNGPOL1, PipaUfs RootLayout.h) at run time, so no policy is compiled in; vr_open refuses a 0-byte manifest (VR_FORMAT),
which keeps the virtio transport (no such device on pipa) from ever serving unverified blocks.

    PIPA_OWNER_ANCHOR=/path/owner.anchor python3 scripts/build-verified-root-key.py --pin <sha256 of the anchor>
The pin must equal the anchor's SHA-256; a CI test key is accepted only with --ci-test-key (and is recorded as such).
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import struct
import subprocess

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument('--pin', required=True, help='SHA-256 of the 395-byte owner anchor')
parser.add_argument('--ci-test-key', action='store_true', help='the anchor is a throwaway CI key: never flash its images')
args = parser.parse_args()

anchor_path = Path(os.environ.get('PIPA_OWNER_ANCHOR', ROOT / 'build/verified-root-key/trusted-key.bin'))
if not anchor_path.is_file():
    raise SystemExit(f'No owner anchor at {anchor_path}: run tools/owner_key.py init and set PIPA_OWNER_ANCHOR')
anchor = anchor_path.read_bytes()
if len(anchor) != 395 or anchor[:8] != b'VROOTKEY' or anchor[392:] != b'\x01\x00\x01' or not anchor[8] & 0x80 or not anchor[391] & 1:
    raise SystemExit('The anchor is not VROOTKEY + a 3072-bit odd modulus + exponent 65537')
digest = hashlib.sha256(anchor).hexdigest()
if digest != args.pin.lower():
    raise SystemExit(f'Anchor SHA-256 {digest} does not match the pin {args.pin}')

out = ROOT / 'build/verified-root-key'
out.mkdir(parents=True, exist_ok=True)
key_copy = out / 'trusted-key.bin'
if key_copy.resolve() != anchor_path.resolve():
    key_copy.write_bytes(anchor)
assembly = out / 'key.S'
assembly.write_text('''// Generated by build-verified-root-key.py: the trusted owner anchor (public) and an empty build-time policy.
.section __DATA_CONST,__const
.balign 8
.globl _verified_root_key
_verified_root_key:
.incbin "''' + str(key_copy) + '''"
.balign 8
.globl _verified_root_manifest, _verified_root_manifest_bytes
_verified_root_manifest:
.byte 0
.balign 8
_verified_root_manifest_bytes:
.quad 0
''')

recipe = ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/bsd/DEVELOPMENT/bsd_init.o.json'
record = json.loads(recipe.read_text().strip().rstrip(','))
objects = []
for source in (ROOT / 'kits/VerifiedRoot/src/verified_root.c', ROOT / 'kits/VerifiedRoot/adapters/xnu_crypto.c'):
    destination = out / (source.stem + '.o')
    compile_args, command, index = record['arguments'], [], 0
    while index < len(compile_args):
        value = compile_args[index]
        if value == record['file']:
            command.append(str(source))
        elif value == '-o':
            command += ['-o', str(destination)]
            index += 1
        elif value in ('-MF', '-MJ'):
            index += 1
        elif value not in ('-MD', '-MP'):
            command.append(value)
        index += 1
    command += ['-I' + str(ROOT / 'kits/VerifiedRoot/include'), '-Werror']
    result = subprocess.run(command, cwd=record['directory'], capture_output=True, text=True)
    (out / (source.stem + '.log')).write_text(result.stdout + result.stderr)
    if result.returncode:
        raise SystemExit(result.stderr[-3500:])
    objects.append(destination)
sdk = subprocess.check_output(['xcrun', '--sdk', 'iphoneos', '--show-sdk-path'], text=True).strip()
subprocess.run(['xcrun', 'clang', '-target', 'arm64-apple-ios17.0', '-isysroot', sdk, '-c', assembly, '-o', out / 'key.o'],
               check=True)
objects.append(out / 'key.o')
for obj in objects:
    data = obj.read_bytes()
    if struct.unpack_from('<4I', data) != (0xfeedfacf, 0x100000c, 0, 1):
        raise SystemExit(f'{obj.name} is not an ordinary ARM64 object')
    cursor, deployment = 32, None
    for _ in range(struct.unpack_from('<I', data, 16)[0]):
        command, length = struct.unpack_from('<II', data, cursor)
        if command == 0x32:
            deployment = struct.unpack_from('<II', data, cursor + 8)
        cursor += length
    if deployment != (2, 0x110000):
        raise SystemExit(f'{obj.name} does not target iOS 17')
symbols = subprocess.check_output(['xcrun', 'nm', '-g', '-j', *map(str, objects)], text=True).split()
for name in ('_verified_root_key', '_verified_root_manifest', '_verified_root_manifest_bytes', '_vr_open', '_vr_verify_block',
             '_vr_xnu_crypto'):
    if name not in symbols:
        raise SystemExit(f'{name} missing from the archive objects')
archive = out / 'libVerifiedRootKey.a'
archive.unlink(missing_ok=True)
subprocess.run(['xcrun', 'ar', 'rcs', archive, *objects], check=True)
(out / 'inputs.json').write_text(json.dumps(dict(
    trusted_key_sha256=digest, ci_test_key=args.ci_test_key, compiled_policy_bytes=0,
    archive_sha256=hashlib.sha256(archive.read_bytes()).hexdigest()), indent=2) + '\n')
print(f'libVerifiedRootKey.a: anchor {digest}{" (CI TEST KEY)" if args.ci_test_key else ""}, verifier and XNU crypto adapter')
